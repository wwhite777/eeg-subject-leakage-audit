#!/usr/bin/env python3
"""Convert the generated figure captions (*_caption.txt, exact-data values) into LaTeX snippets under manuscript/v2/captions/.

Two editorial requirements are enforced here so that they cannot drift from the figures:
  D-10 (EIC): every caption must define the abbreviations it uses. An "Abbreviations:" tail is appended
       listing exactly the abbreviations that occur in the printed caption and are not already defined
       inside it with an explicit "ABBR = ..." phrase.
  D-05.2: a raw "<" or ">" in LaTeX text mode prints as an inverted exclamation/question mark, so tex()
       now escapes them (the Figure 6 caption printed "N ¡ 109" in the submitted PDF).
"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]; SRC = ROOT / "result/figure/revision"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "manuscript/v2/captions"  # revision 2: manuscript/v3/captions
OUT.mkdir(parents=True, exist_ok=True)

# (abbreviation, regex that finds it in the printed caption, expansion)
ABBREVS = [
    ("CSP",   r"\bCSP\b",                 "common spatial patterns"),
    ("LDA",   r"(?<![A-Za-z])LDA\b",      "linear discriminant analysis"),
    ("TS+LR", r"TS\+LR",                  "Riemannian tangent space with logistic regression"),
    ("LR",    r"(?<![+A-Za-z])LR\b",      "logistic regression"),
    ("PCA",   r"\bPCA\b",                 "principal component analysis"),
    ("MDM",   r"\bMDM\b",                 "minimum distance to the Riemannian mean"),
    ("SVM",   r"\bSVM\b",                 "support vector machine"),
    ("k-NN",  r"k-NN",                    "k-nearest neighbours"),
    ("MI",    r"\bMI\b",                  "motor imagery"),
    ("ME",    r"\bME\b",                  "motor execution"),
    ("CI",    r"\bCIs?\b",                "confidence interval"),
    ("LOSO",  r"\bLOSO\b",                "leave-one-subject-out"),
    ("TOST",  r"\bTOST\b",                "two one-sided tests"),
    ("OLS",   r"\bOLS\b",                 "ordinary least squares"),
    ("F1",    r"\bF1\b",                  "number of temporal filters of EEGNet"),
    ("P0",    r"\bP0\b",                  "trial-random split (subject- and run-overlapping)"),
    ("P1",    r"\bP1\b",                  "run-disjoint, subject-overlapping split"),
    ("P1s",   r"\bP1s\b",                 "session-disjoint split"),
    ("P2",    r"\bP2\b",                  "subject-disjoint split"),
]


def abbreviation_tail(text: str) -> str:
    """'Abbreviations: ...' for every abbreviation used in `text` and not already defined inside it."""
    parts = []
    for abbr, pattern, expansion in ABBREVS:
        if not re.search(pattern, text):
            continue
        if re.search(re.escape(abbr) + r"\s*=", text):  # already defined in the caption itself
            continue
        parts.append(f"{abbr} = {expansion}")
    return (" Abbreviations: " + "; ".join(parts) + ".") if parts else ""


def tex(s):
    s = s.replace("\\", "\\textbackslash{}").replace("%", "\\%").replace("&", "\\&").replace("_", "\\_").replace("#", "\\#")
    s = s.replace("Δ", "$\\Delta$").replace("‖", "$\\lVert$").replace("₂", "$_2$").replace("≥", "$\\ge$").replace("≤", "$\\le$").replace("×", "$\\times$").replace("→", "$\\to$").replace("−", "$-$").replace("’", "'")
    s = s.replace("<", "$<$").replace(">", "$>$")  # D-05.2: a raw < prints as "¡"
    s = re.sub(r"\$\\lVert\$w\$\\lVert\$\$_2\$", "$\\\\lVert w\\\\rVert_2$", s)
    return s
tags = (sys.argv[1] if len(sys.argv) > 1 else "rev1").split(",")  # precedence order, e.g. "rev2,rev1": a figure regenerated in revision 2 wins
MACRO = {"fig2": "capFigLadder", "fig3": "capFigWidth", "fig4": "capFigSweep", "fig5": "capFigMechanism", "fig6": "capFigDimension",
         "fig7": "capFigCalibration", "figS1": "capFigBciTwoA", "figS2": "capFigClassifiers"}
lines = ["% generated by make_captions.py from result/figure/revision/*_caption.txt — do not edit"]
for name, macro in MACRO.items():
    cands = next((c for t in tags for c in [sorted(SRC.glob(f"{name}_*_{t}_caption.txt"))] if c), [])
    if not cands:
        lines.append(f"\\newcommand{{\\{macro}}}{{TBD caption ({name})}}")
        print("missing", name); continue
    body = cands[0].read_text().split("\n\nData:")[0].strip()
    body = re.sub(r"^Figure S?\d+\.\s*", "", body)  # LaTeX numbers the figure
    if name != "figS2":  # only figS2 (supplementary figure S1) keeps its value list; figS1 is main-text figure 3
        body = re.sub(r"\s*Values:.*$", "", body, flags=re.S)  # main-text captions: numbers live in the tables
        body += abbreviation_tail(body)
    else:  # supplementary captions keep the values; the tail belongs before them
        head, sep, values = body.partition("Values:")
        head = head.rstrip()
        body = head + abbreviation_tail(head) + ((" " + sep + values) if sep else "")
    lines.append(f"\\newcommand{{\\{macro}}}{{{tex(body)}}}")
    print("wrote", name, "->", macro, len(body), "chars")
(OUT / "captions.tex").write_text("\n".join(lines) + "\n")

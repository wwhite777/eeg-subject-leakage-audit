#!/usr/bin/env python3
"""Convert the generated figure captions (*_caption.txt, exact-data values) into LaTeX snippets under manuscript/v2/captions/."""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]; SRC = ROOT / "result/figure/revision"; OUT = ROOT / "manuscript/v2/captions"; OUT.mkdir(parents=True, exist_ok=True)
def tex(s):
    s = s.replace("\\", "\\textbackslash{}").replace("%", "\\%").replace("&", "\\&").replace("_", "\\_").replace("#", "\\#")
    s = s.replace("Δ", "$\\Delta$").replace("‖", "$\\lVert$").replace("₂", "$_2$").replace("≥", "$\\ge$").replace("≤", "$\\le$").replace("×", "$\\times$").replace("→", "$\\to$").replace("−", "$-$").replace("’", "'")
    s = re.sub(r"\$\\lVert\$w\$\\lVert\$\$_2\$", "$\\\\lVert w\\\\rVert_2$", s)
    return s
tag = sys.argv[1] if len(sys.argv) > 1 else "rev1"
MACRO = {"fig2": "capFigLadder", "fig3": "capFigWidth", "fig4": "capFigSweep", "fig5": "capFigMechanism", "fig6": "capFigDimension",
         "fig7": "capFigCalibration", "figS1": "capFigBciTwoA", "figS2": "capFigClassifiers"}
lines = ["% generated by make_captions.py from result/figure/revision/*_caption.txt — do not edit"]
for name, macro in MACRO.items():
    f = SRC / f"{name}_{'_'.join(name.split('_')[1:]) if False else ''}"  # placeholder
    cands = sorted(SRC.glob(f"{name}_*_{tag}_caption.txt"))
    if not cands:
        lines.append(f"\\newcommand{{\\{macro}}}{{TBD caption ({name})}}")
        print("missing", name); continue
    body = cands[0].read_text().split("\n\nData:")[0].strip()
    body = re.sub(r"^Figure S?\d+\.\s*", "", body)  # LaTeX numbers the figure
    if not name.startswith("figS"):
        body = re.sub(r"\s*Values:.*$", "", body, flags=re.S)  # main-text captions: numbers live in the tables
    lines.append(f"\\newcommand{{\\{macro}}}{{{tex(body)}}}")
    print("wrote", name, "->", macro, len(body), "chars")
(OUT / "captions.tex").write_text("\n".join(lines) + "\n")
